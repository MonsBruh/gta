#!/usr/bin/env python3
"""Resample Terrarium elevation tiles onto the game's local grid -> data/terrain.js

Tiles: https://s3.amazonaws.com/elevation-tiles-prod/terrarium/15/{x}/{y}.png (Mapzen/Tilezen
terrain tiles on AWS Open Data; in England these are derived from Environment Agency LIDAR).
Usage: python3 tools/dem2terrain.py <tile_dir> data/campus.js data/terrain.js
"""
import sys, os, re, json, math, base64
import numpy as np
from PIL import Image

tile_dir, campus_js, out_js = sys.argv[1:4]
Z = 15
SPACING = 3.0  # metres between height samples
src = open(campus_js).read()
origin = json.loads(re.search(r'"origin":(\[[^\]]+\])', src).group(1))
half = json.loads(re.search(r'"half":(\[[^\]]+\])', src).group(1))
LAT0, LON0 = origin
KX = 111320 * math.cos(math.radians(LAT0)); KZ = 110574
HW, HH = half[0] + 40, half[1] + 40

tiles = {}
for f in os.listdir(tile_dir):
    m = re.match(r'(\d+)_(\d+)_(\d+)\.png$', f)
    if m and int(m.group(1)) == Z:
        a = np.asarray(Image.open(os.path.join(tile_dir, f)).convert('RGB')).astype(np.float64)
        tiles[(int(m.group(2)), int(m.group(3)))] = a[..., 0] * 256 + a[..., 1] + a[..., 2] / 256 - 32768
xs = sorted({k[0] for k in tiles}); ys = sorted({k[1] for k in tiles})
mos = np.zeros((len(ys) * 256, len(xs) * 256))
for (tx, ty), a in tiles.items():
    mos[(ty - ys[0]) * 256:(ty - ys[0] + 1) * 256, (tx - xs[0]) * 256:(tx - xs[0] + 1) * 256] = a

nx = int(round(2 * HW / SPACING)) + 1; nz = int(round(2 * HH / SPACING)) + 1
gx = -HW + np.arange(nx) * SPACING; gz = -HH + np.arange(nz) * SPACING
X, Zg = np.meshgrid(gx, gz)
lon = LON0 + X / KX; lat = LAT0 - Zg / KZ
n = 2 ** Z
px = ((lon + 180) / 360 * n - xs[0]) * 256 - 0.5
py = ((1 - np.arcsinh(np.tan(np.radians(lat))) / np.pi) / 2 * n - ys[0]) * 256 - 0.5
x0 = np.clip(np.floor(px).astype(int), 0, mos.shape[1] - 2); y0 = np.clip(np.floor(py).astype(int), 0, mos.shape[0] - 2)
fx = np.clip(px - x0, 0, 1); fy = np.clip(py - y0, 0, 1)
h = (mos[y0, x0] * (1 - fx) * (1 - fy) + mos[y0, x0 + 1] * fx * (1 - fy) + mos[y0 + 1, x0] * (1 - fx) * fy + mos[y0 + 1, x0 + 1] * fx * fy)
# light 3x3 smoothing to remove tile quantisation noise
p = np.pad(h, 1, mode='edge')
h = sum(p[1 + dy:1 + dy + nz, 1 + dx:1 + dx + nx] * w for dy, dx, w in
        [(-1, -1, 1), (-1, 0, 2), (-1, 1, 1), (0, -1, 2), (0, 0, 4), (0, 1, 2), (1, -1, 1), (1, 0, 2), (1, 1, 1)]) / 16
base = float(np.floor(h.min()))
q = np.clip(np.round((h - base) * 100), 0, 65535).astype('<u2')
with open(out_js, 'w') as f:
    f.write('// Generated by tools/dem2terrain.py. Elevation: Tilezen/Mapzen terrain tiles (AWS Open Data), England data from Environment Agency LIDAR (OGL v3).\n')
    f.write('window.TERRAIN=' + json.dumps({'nx': nx, 'nz': nz, 'x0': -HW, 'z0': -HH, 'step': SPACING, 'base': base, 'scale': 0.01,
                                         'data': base64.b64encode(q.tobytes()).decode()}) + ';\n')
print('grid', nx, 'x', nz, 'height range %.1f..%.1f m' % (h.min(), h.max()), 'bytes', os.path.getsize(out_js))
np.save(os.path.join(tile_dir, 'grid.npy'), h)
